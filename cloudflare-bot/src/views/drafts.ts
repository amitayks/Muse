export function renderDeleteDraftConfirm(draftId: string, title: string, lang: Lang = 'en'): ViewResult {
    const safeTitle = escapeHtml(title.length > 60 ? title.substring(0, 57) + '...' : title);
    const text = `${t(lang, 'drafts.deleteDraftTitle')}

<b>${safeTitle}</b>

${t(lang, 'drafts.deleteDraftWarn')}`;

    // Keep under 1024 chars for photo caption compatibility
    const caption = truncateHtml(text, 1024);

    return {
        text: caption,
        keyboard: [
            [
                { text: t(lang, 'common.yesDelete'), callback_data: `action:confirm_delete:${draftId}`, style: 'danger' },
                { text: t(lang, 'common.cancel'), callback_data: `action:cancel_delete:${draftId}`, style: 'danger' },
            ],
        ],
    };
}

